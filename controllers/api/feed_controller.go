func (c feedController) Delete(w http.ResponseWriter, r *http.Request) {
	feedId, err := uuid.Parse(chi.URLParam(r, "id"))
	if err != nil {
		ut.RespondErrorWithJSON(w, http.StatusBadRequest, fmt.Sprintf("Feed is not found: %v", err))
		return
	}

	authUser := mi.BasicApiAuthMiddleware.AuthUser
	if mi.BasicApiAuthMiddleware.Error != nil {
		ut.RespondErrorWithJSON(w, http.StatusForbidden, "Authentication Error!")
		return
	}

	err = cf.DBConnection.DB.DeleteFeed(r.Context(), db.DeleteFeedParams{
		ID:     feedId,
		UserID: authUser.ID,
	})
	if err != nil {
		ut.RespondErrorWithJSON(w, http.StatusBadRequest, fmt.Sprintf("Can not delete feed: %v", err))
		return
	}

	ut.RespondSuccessWithJSON(w, http.StatusCreated, "Feed deleted successfully.")
}
